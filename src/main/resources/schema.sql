-- Timestamps are epoch milliseconds (BIGINT) so the injected java.time.Clock is the only source of time.
CREATE TABLE IF NOT EXISTS payment (
  id           VARCHAR(64)  PRIMARY KEY,
  account_id   VARCHAR(64)  NOT NULL,
  amount_minor BIGINT       NOT NULL,
  currency     VARCHAR(3)   NOT NULL,
  status       VARCHAR(16)  NOT NULL,
  event_seq    BIGINT       NOT NULL,
  created_at   BIGINT       NOT NULL
);

CREATE TABLE IF NOT EXISTS outbox (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aggregate_id    VARCHAR(64)   NOT NULL,
  aggregate_seq   BIGINT        NOT NULL,
  event_type      VARCHAR(64)   NOT NULL,
  payload         VARCHAR(4000) NOT NULL,
  idempotency_key VARCHAR(160)  NOT NULL,
  status          VARCHAR(12)   NOT NULL,
  attempts        INT           NOT NULL,
  next_attempt_at BIGINT        NOT NULL,
  lease_owner     VARCHAR(100),
  lease_until     BIGINT,
  last_error      VARCHAR(500),
  created_at      BIGINT        NOT NULL,
  published_at    BIGINT,
  CONSTRAINT uq_outbox_key UNIQUE (idempotency_key),
  CONSTRAINT uq_outbox_agg_seq UNIQUE (aggregate_id, aggregate_seq)
);
CREATE INDEX IF NOT EXISTS ix_outbox_status ON outbox (status, next_attempt_at);

-- sample consumer side (same database only because this is a single-JVM demo)
CREATE TABLE IF NOT EXISTS processed_message (
  idempotency_key VARCHAR(160) PRIMARY KEY,
  processed_at    BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS account_captured (
  account_id  VARCHAR(64) PRIMARY KEY,
  total_minor BIGINT NOT NULL,
  events      BIGINT NOT NULL
);
